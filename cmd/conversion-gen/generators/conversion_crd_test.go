package generators

import (
	"bytes"
	"strings"
	"testing"

	"k8s.io/gengo/v2/generator"
	"k8s.io/gengo/v2/parser"
	"k8s.io/gengo/v2/types"
)

func TestCRDConversionGeneration(t *testing.T) {
	const (
		alphaPackage = "k8s.io/code-generator/cmd/conversion-gen/generators/internal/testtypes/crd/v1alpha1"
		betaPackage  = "k8s.io/code-generator/cmd/conversion-gen/generators/internal/testtypes/crd/v1beta1"
	)

	builder := parser.New()
	if err := builder.LoadPackages(alphaPackage, betaPackage); err != nil {
		t.Fatal(err)
	}
	universe, err := builder.NewUniverse()
	if err != nil {
		t.Fatal(err)
	}
	alphaTypes, betaTypes := universe[alphaPackage].Types, universe[betaPackage].Types

	getType := func(pkgTypes map[string]*types.Type, name string) *types.Type {
		t.Helper()
		typ, ok := pkgTypes[name]
		if !ok {
			t.Fatalf("type %s not found", name)
		}
		return typ
	}

	alphaSpec := getType(alphaTypes, "WidgetSpec")
	betaSpec := getType(betaTypes, "WidgetSpec")
	alphaPolicy := getType(alphaTypes, "Policy")
	betaPolicy := getType(betaTypes, "Policy")

	conversion := conversionFn()
	conversion.Name = types.Name{Package: betaPackage, Name: "Convert_v1alpha1_Policy_To_v1beta1_Policy"}
	reverseConversion := conversionFn()
	reverseConversion.Name = types.Name{Package: betaPackage, Name: "Convert_v1beta1_Policy_To_v1alpha1_Policy"}
	g := &genConversion{
		typesPackage:  alphaPackage,
		outputPackage: betaPackage,
		manualConversions: conversionFuncMap{
			{alphaPolicy, betaPolicy}: conversion,
			{betaPolicy, alphaPolicy}: reverseConversion,
		},
		imports:   generator.NewImportTrackerForPackage(betaPackage),
		useUnsafe: equalMemoryTypes{},
	}
	if !g.convertibleOnlyWithinPackage(getType(alphaTypes, "Label"), getType(betaTypes, "DisplayLabel")) {
		t.Fatal("named scalar types should be eligible for generated conversions")
	}

	ctx := &generator.Context{}
	ctx.Namers = g.Namers(ctx)
	generate := func(inType, outType *types.Type) string {
		t.Helper()
		var generated bytes.Buffer
		sw := generator.NewSnippetWriter(&generated, ctx, "$", "$")
		g.generateFor(inType, outType, false, sw)
		if err := sw.Error(); err != nil {
			t.Fatal(err)
		}
		return generated.String()
	}
	code := generate(alphaSpec, betaSpec)
	reverseCode := generate(betaSpec, alphaSpec)
	settingsCode := generate(getType(alphaTypes, "Settings"), getType(betaTypes, "Settings"))
	labelCode := generate(getType(alphaTypes, "Label"), getType(betaTypes, "DisplayLabel"))
	replicaCode := generate(getType(alphaTypes, "ReplicaCount"), getType(betaTypes, "DesiredReplicas"))

	for _, want := range []string{
		"in.Name",
		"out.Title",
		"DisplayLabel",
		"DesiredReplicas",
		"RuleKey",
		"RuleText",
	} {
		if !strings.Contains(code, want) {
			t.Errorf("generated conversion does not contain %q:\n%s", want, code)
		}
	}

	if !strings.Contains(reverseCode, "in.Title") || !strings.Contains(reverseCode, "out.Name") {
		t.Errorf("generated reverse conversion did not honor the field rename:\n%s", reverseCode)
	}
	if !strings.Contains(labelCode, "DisplayLabel(*in)") {
		t.Errorf("generated named-string conversion is missing its direct conversion:\n%s", labelCode)
	}
	if !strings.Contains(replicaCode, "DesiredReplicas(*in)") {
		t.Errorf("generated named-integer conversion is missing its direct conversion:\n%s", replicaCode)
	}
	if !strings.Contains(settingsCode, "Convert_v1alpha1_Policy_To_v1beta1_Policy") {
		t.Errorf("generated nested conversion does not invoke the manual Policy conversion:\n%s", settingsCode)
	}
	if strings.Contains(code, "out = (*Settings)(unsafe.Pointer(in))") ||
		strings.Contains(settingsCode, "unsafe.Pointer") {
		t.Errorf("generated conversion used an unsafe copy and bypassed the nested Policy conversion:\n%s\n%s", code, settingsCode)
	}
}
